"""
Task generator — follow-up tasks driven by score category + consent.

Rules (U2):
  - HOT  → task with SLA 1h, priority URGENT
  - WARM → task with SLA 24h, priority HIGH
  - NURTURE → task with SLA 72h, priority MEDIUM
  - COLD → no sales task created (nurture drip only, out of scope)

Consent enforcement (A1/A6):
  - Task is created ONLY if the lead has at least one GRANTED consent channel.
  - Task stores `consent_eligible` snapshot for audit.
"""
from __future__ import annotations

from datetime import timedelta

from faker import Faker
from sqlalchemy.orm import Session

from backend.app.data_generator import config as cfg
from backend.app.data_generator.ids import task_id
from backend.app.models.enums import (
    ConsentChannel,
    ConsentStatus,
    LeadStatus,
    ScoreCategory,
    TaskPriority,
    TaskStatus,
)
from backend.app.models.marketing import Consent, Lead
from backend.app.models.sales_ops import Task


_PRIORITY_BY_CAT = {
    ScoreCategory.HOT: TaskPriority.URGENT,
    ScoreCategory.WARM: TaskPriority.HIGH,
    ScoreCategory.NURTURE: TaskPriority.MEDIUM,
}
_RULE_BY_CAT = {
    ScoreCategory.HOT: "score_hot_immediate",
    ScoreCategory.WARM: "score_warm_24h",
    ScoreCategory.NURTURE: "nurture_scheduled",
}
_STATUS_BY_SCORE_CAT = {
    ScoreCategory.HOT: [LeadStatus.QUALIFIED, LeadStatus.ASSIGNED, LeadStatus.WORKING],
    ScoreCategory.WARM: [LeadStatus.QUALIFIED, LeadStatus.ASSIGNED, LeadStatus.WORKING],
    ScoreCategory.NURTURE: [LeadStatus.SCORED, LeadStatus.QUALIFIED],
}


def _has_any_consent(db: Session, lead_id: int) -> bool:
    return (
        db.query(Consent)
        .filter(
            Consent.lead_id == lead_id,
            Consent.status == ConsentStatus.GRANTED,
        )
        .first()
        is not None
    )


def generate_tasks(
    db: Session,
    leads: list[Lead],
    seed: int,
) -> list[Task]:
    fake = Faker()
    Faker.seed(seed + 8)

    tasks: list[Task] = []
    # Batch-fetch consent map for speed
    lead_ids = [l.id for l in leads]
    consents_by_lead: dict[int, bool] = {}
    for c in (
        db.query(Consent)
        .filter(Consent.lead_id.in_(lead_ids))
        .filter(Consent.status == ConsentStatus.GRANTED)
        .all()
    ):
        consents_by_lead[c.lead_id] = True

    for lead in leads:
        cat = lead.current_score_category
        if cat not in _PRIORITY_BY_CAT:
            continue  # COLD → no sales task
        if lead.status not in _STATUS_BY_SCORE_CAT.get(cat, []):
            continue  # Only create tasks for leads past SCORED
        if not consents_by_lead.get(lead.id):
            continue  # A6: no task if no consent
        if lead.assigned_rep_id is None:
            continue  # Task must have an owner — spec: task ownership validation

        sla_hours = cfg.TASK_SLA_HOURS[cat.value]
        created = lead.assigned_at or lead.created_at
        due_at = created + timedelta(hours=sla_hours)
        sla_deadline_at = due_at  # for hot/warm/nurture it's the same

        tasks.append(
            Task(
                business_id=task_id(lead.business_id, 1),
                lead_id=lead.id,
                assigned_rep_id=lead.assigned_rep_id,
                title=f"Follow up with {cat.value} lead ({lead.business_id})",
                description=f"Auto-generated by rule {_RULE_BY_CAT[cat]}. SLA {sla_hours}h.",
                priority=_PRIORITY_BY_CAT[cat],
                status=TaskStatus.PENDING,
                due_at=due_at,
                sla_deadline_at=sla_deadline_at,
                completed_at=None,
                consent_eligible=True,
                triggering_rule=_RULE_BY_CAT[cat],
                created_at=created,
                updated_at=created,
            )
        )

    db.add_all(tasks)
    db.flush()
    return tasks

