"""
Follow-up task engine.

create_followup_task(lead, db) → Task | None

Business rules (A1 + U2):
  - HOT leads     → URGENT task, SLA 1 hour
  - WARM leads    → HIGH task,   SLA 24 hours
  - NURTURE leads → MEDIUM task, SLA 72 hours
  - COLD leads    → no sales task (returns None)
  - No task if lead has no assigned rep
  - No task if lead has no channel with GRANTED consent (A1 hard gate)

Consent is checked BEFORE task creation. Task stores consent_eligible=True
snapshot for audit. If consent is later revoked, existing tasks remain (they
are historical) but the rep must respect the current state.

Every task writes:
  - business_id (TASK-<lead>-<seq>)
  - due_at + sla_deadline_at
  - triggering_rule (e.g. "score_hot_immediate")
  - consent_eligible snapshot
"""
from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime, timedelta, timezone

from sqlalchemy.orm import Session

from backend.app.models.enums import (
    ConsentChannel,
    ConsentStatus,
    LeadStatus,
    ScoreCategory,
    TaskPriority,
    TaskStatus,
)
from backend.app.models.marketing import Consent, Lead
from backend.app.models.sales_ops import Task


# Score category → task profile (U2)
_TASK_PROFILE: dict[ScoreCategory, dict] = {
    ScoreCategory.HOT: {
        "priority": TaskPriority.URGENT,
        "sla_hours": 1,
        "triggering_rule": "score_hot_immediate",
    },
    ScoreCategory.WARM: {
        "priority": TaskPriority.HIGH,
        "sla_hours": 24,
        "triggering_rule": "score_warm_24h",
    },
    ScoreCategory.NURTURE: {
        "priority": TaskPriority.MEDIUM,
        "sla_hours": 72,
        "triggering_rule": "nurture_scheduled",
    },
    # COLD: no task
}


@dataclass
class ConsentSnapshot:
    email: ConsentStatus | None = None
    phone: ConsentStatus | None = None
    sms: ConsentStatus | None = None
    marketing: ConsentStatus | None = None

    @property
    def any_granted(self) -> bool:
        return any(
            s == ConsentStatus.GRANTED
            for s in (self.email, self.phone, self.sms, self.marketing)
        )


def _get_consent_snapshot(db: Session, lead_id: int, as_of: datetime) -> ConsentSnapshot:
    """Latest consent row per channel, at or before `as_of`."""
    snap = ConsentSnapshot()
    for channel in (ConsentChannel.EMAIL, ConsentChannel.PHONE,
                    ConsentChannel.SMS, ConsentChannel.MARKETING):
        row = (
            db.query(Consent)
            .filter(
                Consent.lead_id == lead_id,
                Consent.channel == channel,
                Consent.changed_at <= as_of,
            )
            .order_by(Consent.changed_at.desc())
            .first()
        )
        if row is not None:
            setattr(snap, channel.value, row.status)
    return snap


def _next_task_seq(db: Session, lead_id: int) -> int:
    """Return N for TASK-<lead>-<N> (existing count + 1)."""
    n = db.query(Task).filter(Task.lead_id == lead_id).count()
    return n + 1


def _build_business_id(lead: Lead, seq: int) -> str:
    return f"TASK-{lead.business_id}-{seq:03d}"


def create_followup_task(
    db: Session,
    lead: Lead,
    as_of: datetime | None = None,
) -> Task | None:
    """
    Create a follow-up task for the lead, or return None if ineligible.

    Eligibility gates (in order):
      1. Lead must have a score category in {HOT, WARM, NURTURE}
      2. Lead must have an assigned rep
      3. Lead status must be past SCORED (must be QUALIFIED, ASSIGNED, WORKING)
      4. At least one consent channel GRANTED

    Returns the created Task (flushed, not committed) or None.
    """
    as_of = as_of or datetime.now(timezone.utc)

    cat = lead.current_score_category
    if cat is None or cat not in _TASK_PROFILE:
        return None  # COLD or unscored → no task

    if lead.assigned_rep_id is None:
        return None  # no owner → no task

    if lead.status not in (LeadStatus.QUALIFIED, LeadStatus.ASSIGNED, LeadStatus.WORKING):
        return None  # must be in-flight to warrant a task

    snap = _get_consent_snapshot(db, lead.id, as_of)
    if not snap.any_granted:
        return None  # A1 HARD GATE — no task if all channels revoked

    profile = _TASK_PROFILE[cat]
    created_at = as_of
    due_at = created_at + timedelta(hours=profile["sla_hours"])

    task = Task(
        business_id=_build_business_id(lead, _next_task_seq(db, lead.id)),
        lead_id=lead.id,
        assigned_rep_id=lead.assigned_rep_id,
        title=f"Follow up with {cat.value} lead ({lead.business_id})",
        description=(
            f"Auto-generated by rule {profile['triggering_rule']}. "
            f"SLA {profile['sla_hours']}h. Consent: "
            f"email={snap.email.value if snap.email else 'none'}, "
            f"phone={snap.phone.value if snap.phone else 'none'}"
        ),
        priority=profile["priority"],
        status=TaskStatus.PENDING,
        due_at=due_at,
        sla_deadline_at=due_at,
        completed_at=None,
        consent_eligible=True,  # snapshot: at least one channel was granted
        triggering_rule=profile["triggering_rule"],
        created_at=created_at,
        updated_at=created_at,
    )
    db.add(task)
    db.flush()
    return task

